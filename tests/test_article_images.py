"""Иллюстрации статьи: провайдер, кэш и лицензия в артефакте (этап I4).

Что здесь проверяется — и почему именно это:

1. **Доступность считается, а не объявлена.** Без `MEDIA_IMAGE_PROVIDER_KEY` провайдер
   недоступен, и это видно в витрине с именами переменных, а не «картинки нет».
2. **Без лицензии иллюстрация не публикуется.** Ответ провайдера без `license` — отказ
   `license_missing`: статья с чужой картинкой без прав хуже статьи без картинки.
3. **Кэш по содержимому запроса.** Одинаковый промпт не оплачивается дважды; в записи кэша
   лежит лицензия, поэтому подпись под иллюстрацией не нужно «восстанавливать по памяти».
4. **Откат честный.** Нет ключа — статья собирается со своей графикой (`brand-card`), а в спеке
   остаётся `fallback_reason`. Пользователь видит, почему картинка нарисована, а не снята.
5. **Неизвестный провайдер отвергается** (`image_provider_unknown`), как пакет и шаблон.
"""
from __future__ import annotations

import pytest
from fastapi.testclient import TestClient

from orbita import articles
from orbita.main import app

client = TestClient(app)
H = {"X-Actor-Role": "owner"}

TEXT = ("Разбираем по существу, как выглядит отчёт и что в нём важно, чтобы не платить "
        "за пустой охват. ") * 12

PROVIDER_ANSWER = {
    "ok": True, "url": "https://cdn.example.com/art/otchet.png", "width": 1600, "height": 900,
    "license": {"name": "Generated by ExampleAI", "type": "generated",
                "terms_url": "https://example.com/terms", "author": "ExampleAI"},
    "cost_rub": 2.4,
}


@pytest.fixture(autouse=True)
def _clean(monkeypatch):
    for name in ("MEDIA_IMAGE_PROVIDER_KEY", "MEDIA_IMAGE_PROVIDER_URL",
                 "MEDIA_STOCK_KEY", "MEDIA_STOCK_URL"):
        monkeypatch.delenv(name, raising=False)
    articles.reset()
    articles.reset_images()
    yield
    articles.reset()
    articles.reset_images()


def _enable(monkeypatch) -> None:
    monkeypatch.setenv("MEDIA_IMAGE_PROVIDER_KEY", "test-key")
    monkeypatch.setenv("MEDIA_IMAGE_PROVIDER_URL", "https://provider.example.com/generate")


def _brief(**overrides) -> dict:
    brief = {
        "topic": "Отчёт по охватам: что в нём важно",
        "keywords": ["отчёт по охватам"],
        "sections": 3,
        "lead": "Отчёт по охватам: что смотреть в первую очередь.",
        "outline": [
            {"heading": "Как выглядит отчёт", "text": TEXT,
             "image_prompt": "Отчёт по охватам в кабинете клиента"},
            {"heading": "Сколько это стоит", "text": TEXT,
             "columns": ["Пакет", "Цена"], "rows": [["Базовый", "9 000 ₽"]],
             "source": "прайс клиента"},
            {"heading": "Что дальше", "text": TEXT},
        ],
        "faq": [{"q": "Как часто делать отчёт?", "a": "Раз в неделю."}],
    }
    brief.update(overrides)
    return brief


# ---------------------------------------------------------------- реестр и отказы
def test_catalog_availability_comes_from_environment(monkeypatch):
    codes = {row["code"]: row for row in articles.image_catalog()}
    assert codes["brand-card"]["available"] is True
    assert codes["ai-generate"]["available"] is False
    assert "MEDIA_IMAGE_PROVIDER_KEY" in codes["ai-generate"]["needs"]
    _enable(monkeypatch)
    codes = {row["code"]: row for row in articles.image_catalog()}
    assert codes["ai-generate"]["available"] is True
    assert codes["ai-generate"]["needs"] == []
    assert codes["stock"]["available"] is False


def test_brand_card_always_works_and_is_own_graphic():
    made = articles.generate_image("Отчёт в кабинете")
    assert made["ok"] and made["provider"] == "brand-card"
    assert made["asset"]["props"]
    assert made["license"]["type"] == "own"


def test_missing_key_refusal_names_variables():
    refused = articles.generate_image("Отчёт", provider="ai-generate")
    assert refused["ok"] is False and refused["code"] == "provider_key_missing"
    assert "MEDIA_IMAGE_PROVIDER_KEY" in refused["needs"]
    assert "MEDIA_IMAGE_PROVIDER_KEY" in refused["reason"]


def test_unknown_provider_and_empty_prompt_are_rejected():
    assert articles.generate_image("Отчёт", provider="midjourney")["code"] == "provider_unknown"
    assert articles.generate_image("   ", provider="brand-card")["code"] == "prompt_required"


def test_provider_answer_without_license_is_refused(monkeypatch):
    _enable(monkeypatch)
    monkeypatch.setattr(articles, "_provider_request",
                        lambda provider, prompt, size: {"ok": True, "url": "https://x/y.png",
                                                        "license": {}})
    refused = articles.generate_image("Отчёт", provider="ai-generate")
    assert refused["code"] == "license_missing"
    assert articles.image_cache_stats()["entries"] == 0


def test_provider_failures_do_not_crash(monkeypatch):
    _enable(monkeypatch)
    monkeypatch.setattr(articles, "_provider_request",
                        lambda provider, prompt, size: {"ok": False, "code": "provider_failed",
                                                        "reason": "timeout"})
    assert articles.generate_image("Отчёт", provider="ai-generate")["code"] == "provider_failed"
    monkeypatch.setattr(articles, "_provider_request",
                        lambda provider, prompt, size: {"ok": False,
                                                        "code": "provider_response_invalid",
                                                        "reason": "no url"})
    assert articles.generate_image("Отчёт", provider="ai-generate")["code"] == (
        "provider_response_invalid")


# ---------------------------------------------------------------- кэш и лицензия
def test_cache_returns_same_entry_and_records_license(monkeypatch):
    _enable(monkeypatch)
    calls: list[str] = []

    def fake(provider, prompt, size):
        calls.append(prompt)
        return dict(PROVIDER_ANSWER)

    monkeypatch.setattr(articles, "_provider_request", fake)
    first = articles.generate_image("Отчёт в кабинете", provider="ai-generate")
    second = articles.generate_image("Отчёт в кабинете", provider="ai-generate")
    assert first["ok"] and not first["cached"]
    assert second["cached"] and second["url"] == first["url"]
    assert len(calls) == 1, "второй одинаковый запрос не должен уходить провайдеру"
    cache = articles.image_cache()
    assert len(cache) == 1
    assert cache[0]["license"]["name"] == "Generated by ExampleAI"
    stats = articles.image_cache_stats()
    assert stats["entries"] == 1 and stats["cost_rub"] == 2.4
    assert stats["providers"] == {"ai-generate": 1}


def test_cache_key_depends_on_prompt_and_size():
    one = articles.image_key("ai-generate", "Отчёт", "16x9")
    two = articles.image_key("ai-generate", "Отчёт", "1x1")
    assert one != two
    assert one == articles.image_key("ai-generate", " Отчёт ", "16x9")


# ---------------------------------------------------------------- статья
def test_article_uses_external_image_with_attribution(monkeypatch):
    _enable(monkeypatch)
    monkeypatch.setattr(articles, "_provider_request",
                        lambda provider, prompt, size: dict(PROVIDER_ANSWER))
    result = articles.compose(_brief(image_provider="ai-generate"))
    spec = result["spec"]
    assert spec["image_provider"] == "ai-generate"
    image = next(block for block in spec["blocks"] if block["type"] == "image")
    assert image["props"]["provider"] == "ai-generate"
    assert image["props"]["image"]["url"].startswith("https://cdn.example.com")
    assert articles.attribution(image) == "Generated by ExampleAI · провайдер: ai-generate"
    assert result["checks"]["ok"], result["checks"]["issues"]
    html = articles.render_html(spec)
    assert '<img src="https://cdn.example.com/art/otchet.png"' in html
    assert 'alt="Отчёт по охватам в кабинете клиента"' in html
    assert "Generated by ExampleAI" in html


def test_article_falls_back_to_brand_card_with_reason():
    result = articles.compose(_brief(image_provider="ai-generate"))
    spec = result["spec"]
    image = next(block for block in spec["blocks"] if block["type"] == "image")
    assert image["props"]["provider"] == "brand-card"
    assert image["props"]["requested_provider"] == "ai-generate"
    assert "MEDIA_IMAGE_PROVIDER_KEY" in image["props"]["fallback_reason"]
    assert result["checks"]["ok"]
    assert "<img" not in articles.render_html(spec)


def test_external_image_without_license_is_reported():
    spec = articles.compose(_brief())["spec"]
    image = next(block for block in spec["blocks"] if block["type"] == "image")
    image["props"] = {"prompt": "Отчёт", "provider": "ai-generate",
                      "image": {"url": "https://cdn.example.com/x.png", "provider": "ai-generate",
                                "license": {}}}
    codes = {issue["code"] for issue in articles.check(spec)["issues"]}
    assert "license_missing" in codes


def test_policy_requires_attribution_when_asked():
    spec = articles.compose(_brief())["spec"]
    image = next(block for block in spec["blocks"] if block["type"] == "image")
    image["props"] = {"prompt": "Отчёт", "provider": "ai-generate",
                      "image": {"url": "https://cdn.example.com/x.png", "provider": "",
                                "license": {}}}
    spec["policy"] = {"require_attribution": True}
    codes = {issue["code"] for issue in articles.check(spec)["issues"]}
    assert {"license_missing", "attribution_missing"} <= codes


# ---------------------------------------------------------------- API
def test_api_rejects_unknown_provider_and_lists_catalog():
    rejected = client.post("/api/v1/articles", headers=H,
                           json={"topic": "Тема иллюстраций", "sections": 3,
                                 "image_provider": "midjourney"})
    assert rejected.status_code == 422
    assert rejected.json()["detail"]["kind"] == "image_provider_unknown"
    body = client.get("/api/v1/articles/images", headers=H).json()
    assert {row["code"] for row in body["providers"]} == {"brand-card", "ai-generate", "stock"}
    assert body["default"] == "brand-card"
    assert "MEDIA_IMAGE_PROVIDER_KEY" in body["env"]["keys"]
    assert body["cache"]["entries"] == 0


def test_api_accepts_provider_and_reports_fallback():
    created = client.post("/api/v1/articles", headers=H,
                          json=_brief(materials=[], strict=False, image_provider="stock"))
    assert created.status_code == 201, created.text
    image = next(block for block in created.json()["spec"]["blocks"]
                 if block["type"] == "image")
    assert image["props"]["requested_provider"] == "stock"
    assert image["props"]["fallback_reason"]
