"""Демо этапа I4: иллюстрации из провайдера — с кэшем, лицензией и честным откатом.

Что показывает скрипт:

1. **Без ключа — отказ и своя графика.** Провайдер `ai-generate` недоступен, статья всё равно
   собирается: иллюстрацию рисует медиа-движок, а в спеке остаётся `fallback_reason` с именем
   переменной. Читатель видит карточку, редактор — причину.
2. **С ключом — файл с лицензией.** Провайдер отвечает ссылкой и лицензией; запись кэша хранит
   и то и другое, поэтому подпись под иллюстрацией не восстанавливается «по памяти».
3. **Кэш по содержимому.** Одинаковый промпт не оплачивается дважды: второй вызов возвращает
   `cached: true` и не уходит в сеть (в демо провайдер эмулируется счётчиком вызовов).
4. **Без лицензии — не публикуем.** Ответ без прав отвергается кодом `license_missing`.

Провайдер в демо эмулируется: в песочнице нет ни ключа, ни адреса генератора. Это тот же путь,
что в проде — меняется только источник ответа, а не конвейер: запрос → лицензия → кэш → блок.

Запуск (из 40-BACKEND):
    PYTHONPATH=src DATA_LAYER=memory python scripts/demo_article_images.py
"""
from __future__ import annotations

import io
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from orbita import articles  # noqa: E402

OUT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..",
                                   "20-DESIGN", "articles", "backend"))

TOPIC = "Отчёт по охватам: что в нём важно и как его читать"

TEXT = (
    "Отчёт нужен не для того, чтобы показать цифры, а чтобы принять решение: оставить канал, "
    "поменять формат или остановиться. Поэтому в отчёте три строки важнее остальных: сколько "
    "человек увидели пост, сколько перешли по ссылке и сколько из перешедших сделали целевое "
    "действие. Первая строка отвечает на вопрос «нас видно?», вторая — «нас читают?», третья — "
    "«нам верят?». Если хотя бы одна строка пустая, отчёт превращается в украшение.")

BRIEF = {
    "topic": TOPIC,
    "seo_title": "Отчёт по охватам: строки, которые решают",
    "keywords": ["отчёт по охватам", "аналитика каналов"],
    "sections": 4,
    "lead": ("Отчёт по охватам: какие три строки решают судьбу канала и как выглядит отчёт, "
             "который не стыдно показать руководству."),
    "outline": [
        {"heading": "Как выглядит отчёт в кабинете", "text": TEXT,
         "image_prompt": "Отчёт по охватам и переходам в кабинете клиента"},
        {"heading": "Три строки, которые решают", "text": TEXT},
        {"heading": "Сколько стоит отчёт", "text": TEXT,
         "columns": ["Пакет", "Что входит", "Цена"],
         "rows": [["Базовый", "охваты и переходы", "0 ₽"],
                  ["Расширенный", "плюс цена действия", "3 900 ₽"]],
         "source": "прайс клиента, ноябрь 2026"},
        {"heading": "Что делать с отчётом", "text": TEXT,
         "steps": ["Сверить охваты", "Посчитать цену действия", "Оставить или сменить канал"]},
    ],
    "summary": ["Охваты, переходы и действие — три строки отчёта",
                "Отчёт без цены действия не отвечает на главный вопрос",
                "Канал меняют по данным, а не по вкусу"],
    "faq": [{"q": "Как часто нужен отчёт?", "a": "Раз в неделю: чаще — шум, реже — поздно."}],
    "cta": "Открыть отчёт по своим каналам",
    "cta_url": "/pricing",
    "canonical": "https://example.com/blog/otchet-po-ohvatam/",
}

#: ответ «провайдера» для демо: в песочнице нет ни ключа, ни адреса генератора
PROVIDER_ANSWER = {
    "ok": True, "url": "https://cdn.example.com/art/otchet-ohvaty.png",
    "width": 1600, "height": 900,
    "license": {"name": "Generated by ExampleAI", "type": "generated",
                "terms_url": "https://example.com/terms", "author": "ExampleAI"},
    "cost_rub": 2.4,
}


def build(name: str, *, provider: str) -> dict:
    result = articles.compose({**BRIEF, "image_provider": provider})
    if not result.get("ok"):
        raise SystemExit(f"статья не собралась: {result}")
    spec, checks = result["spec"], result["checks"]
    html = articles.render_html(spec)
    page = os.path.join(OUT, f"demo-article-images-{name}.html")
    with open(page, "w", encoding="utf-8") as handle:
        handle.write(html)
    with open(os.path.join(OUT, f"demo-article-images-{name}.spec.json"), "w",
              encoding="utf-8") as handle:
        json.dump(spec, handle, ensure_ascii=False, indent=2)
    return {"spec": spec, "checks": checks, "page": page, "html": html}


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    saved = {name: os.environ.get(name) for name in
             ("MEDIA_IMAGE_PROVIDER_KEY", "MEDIA_IMAGE_PROVIDER_URL")}
    articles.reset()
    articles.reset_images()
    try:
        # 1. без ключа: отказ + своя графика + причина в спеке
        for name in saved:
            os.environ.pop(name, None)
        refused = articles.generate_image("Отчёт в кабинете", provider="ai-generate")
        fallback = build("fallback", provider="ai-generate")
        image = next(block for block in fallback["spec"]["blocks"] if block["type"] == "image")

        # 2. «ключ есть»: провайдер эмулируется, лицензия и кэш — настоящие
        os.environ["MEDIA_IMAGE_PROVIDER_KEY"] = "demo-key"
        os.environ["MEDIA_IMAGE_PROVIDER_URL"] = "https://provider.example.com/generate"
        calls = {"count": 0}
        original = articles._provider_request

        def fake(provider: str, prompt: str, size: str) -> dict:
            calls["count"] += 1
            return dict(PROVIDER_ANSWER)

        articles._provider_request = fake
        try:
            licensed = build("licensed", provider="ai-generate")
            cached = articles.generate_image("Отчёт по охватам и переходам в кабинете клиента",
                                             provider="ai-generate")
            articles._provider_request = lambda provider, prompt, size: {
                "ok": True, "url": "https://cdn.example.com/art/nolicense.png", "license": {}}
            naked = articles.generate_image("Промпт без лицензии", provider="ai-generate")
        finally:
            articles._provider_request = original

        external = next(block for block in licensed["spec"]["blocks"] if block["type"] == "image")
        report = {
            "topic": TOPIC,
            "without_key": {"refusal": refused,
                            "block_provider": image["props"]["provider"],
                            "requested": image["props"]["requested_provider"],
                            "fallback_reason": image["props"]["fallback_reason"]},
            "with_key": {"url": external["props"]["image"]["url"],
                         "license": external["props"]["image"]["license"],
                         "attribution": articles.attribution(external),
                         "cached": external["props"]["image"]["cached"],
                         "second_call_cached": bool(cached.get("cached")),
                         "provider_calls": calls["count"]},
            "cache": articles.image_cache_stats(),
            "without_license": naked,
            "checks": {name: row["checks"] for name, row in
                       (("fallback", fallback), ("licensed", licensed))},
        }
        with open(os.path.join(OUT, "demo-article-images-report.json"), "w",
                  encoding="utf-8") as handle:
            json.dump(report, handle, ensure_ascii=False, indent=2)

        print(f"без ключа: {refused['code']} — {refused['reason']}")
        print(f"  статья собрана со своей графикой, причина в спеке: "
              f"{image['props']['fallback_reason']}")
        print(f"с ключом: {external['props']['image']['url']}")
        print(f"  лицензия: {external['props']['image']['license']['name']}, "
              f"подпись: «{articles.attribution(external)}»")
        print(f"  кэш: {report['cache']['entries']} записей, провайдер вызван "
              f"{calls['count']} раз(а); повторный запрос из кэша: "
              f"{'да' if cached.get('cached') else 'нет'}")
        print(f"без лицензии: {naked['code']} — иллюстрация не создана")
        print(f"HTML: {fallback['page']}")
        print(f"HTML: {licensed['page']}")
    finally:
        for name, value in saved.items():
            if value is None:
                os.environ.pop(name, None)
            else:
                os.environ[name] = value
        articles.reset()
        articles.reset_images()


if __name__ == "__main__":
    main()
